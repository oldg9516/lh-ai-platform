"""Admin API for instruction updates (Phase 9.2).

Provides endpoints to list, review, approve, reject, and deploy
instruction update suggestions generated by the pattern detector.
"""

import structlog
from fastapi import APIRouter, HTTPException, Query

from database.queries import (
    get_instruction_updates,
    get_instruction_update,
    update_instruction_status,
)
from learning.pattern_detector import run_pattern_analysis

logger = structlog.get_logger()

router = APIRouter()

# Valid status transitions
_VALID_TRANSITIONS = {
    "pending": {"approved", "rejected"},
    "approved": {"deployed", "rejected"},
}


@router.get("/instruction-updates")
async def list_instruction_updates(
    status: str | None = Query(None, description="Filter by status"),
    category: str | None = Query(None, description="Filter by category"),
) -> list[dict]:
    """List instruction update suggestions with optional filters."""
    return get_instruction_updates(status=status, category=category)


@router.get("/instruction-updates/{update_id}")
async def get_update(update_id: str) -> dict:
    """Get a single instruction update by ID."""
    record = get_instruction_update(update_id)
    if not record:
        raise HTTPException(status_code=404, detail="Instruction update not found")
    return record


@router.post("/instruction-updates/{update_id}/approve")
async def approve_update(update_id: str) -> dict:
    """Approve a pending instruction update."""
    return _transition(update_id, "approved")


@router.post("/instruction-updates/{update_id}/reject")
async def reject_update(update_id: str) -> dict:
    """Reject a pending or approved instruction update."""
    return _transition(update_id, "rejected")


@router.post("/instruction-updates/{update_id}/deploy")
async def deploy_update(update_id: str) -> dict:
    """Deploy an approved instruction update into agent instructions."""
    return _transition(update_id, "deployed")


@router.post("/instruction-updates/analyze")
async def trigger_analysis() -> dict:
    """Trigger pattern analysis and generate instruction fix suggestions."""
    created_ids = await run_pattern_analysis()
    return {
        "created": len(created_ids),
        "update_ids": created_ids,
    }


def _transition(update_id: str, target_status: str) -> dict:
    """Validate and execute a status transition.

    Args:
        update_id: UUID of the instruction update.
        target_status: Desired new status.

    Returns:
        Updated record dict.

    Raises:
        HTTPException: If record not found or transition invalid.
    """
    record = get_instruction_update(update_id)
    if not record:
        raise HTTPException(status_code=404, detail="Instruction update not found")

    current_status = record["status"]
    allowed = _VALID_TRANSITIONS.get(current_status, set())
    if target_status not in allowed:
        raise HTTPException(
            status_code=400,
            detail=f"Cannot transition from '{current_status}' to '{target_status}'. "
            f"Allowed: {sorted(allowed) if allowed else 'none'}",
        )

    updated = update_instruction_status(update_id, target_status)
    if not updated:
        raise HTTPException(status_code=500, detail="Failed to update status")

    logger.info(
        "instruction_update_status_changed",
        update_id=update_id,
        from_status=current_status,
        to_status=target_status,
        category=record["category"],
    )
    return updated
